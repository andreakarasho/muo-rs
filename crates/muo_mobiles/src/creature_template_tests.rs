#[test]
fn converted_classes_have_templates() {
    let mut w = crate::test_world();
    let t = templates::table(&mut w);
    for name in CONVERTED {
        assert!(
            t.get(Kind::Mobile, name).is_some(),
            "{name} has no template"
        );
    }
    for name in MOUNTS {
        let props = &t.get(Kind::Mobile, name).unwrap().props;
        assert!(
            props.contains_key("mountBody") && props.contains_key("mountItemId"),
            "{name}: mount props"
        );
    }
}

#[test]
fn enum_props_parse() {
    let mut w = crate::test_world();
    let t = templates::table(&mut w);
    let bad = crate::cprops::bad_enum_props(&t);
    assert!(bad.is_empty(), "{bad:?}");
}
