    fn encodes_every_symbol_matching_canonical_table() {
        let input: Vec<u8> = (0..=255u8).collect();
        let mut output = [0u8; 512];
        let length = compress(&input, &mut output);
        assert_eq!(length, ALL_SYMBOLS_COMPRESSED.len());
        assert_eq!(&output[..length], ALL_SYMBOLS_COMPRESSED);
    }

    #[test]
    fn refuses_output_too_small_to_bound() {
        let input = [b'A'; 64];
        for size in 0..4 {
            let mut backing = [0xCCu8; 256];
            let written = compress(&input, &mut backing[64..64 + size]);
            assert_eq!(written, 0);
            assert!(backing.iter().all(|&b| b == 0xCC));
        }
    }

    #[test]
    fn reports_failure_rather_than_overrunning_a_tight_output() {
        let input = [b'A'; 4096];
        let mut backing = [0xCCu8; 256];
        compress(&input, &mut backing[64..80]);
        assert!(backing[..64].iter().all(|&b| b == 0xCC));
        assert!(backing[80..].iter().all(|&b| b == 0xCC));
    }

    #[test]
    fn empty_input_is_just_the_terminal_code() {
        let mut out = [0u8; 8];
        // terminal 0xD in 4 bits, padded to a byte: 0xD0
        assert_eq!(compress(&[], &mut out), 1);
        assert_eq!(out[0], 0xD0);
    }

    #[test]
    fn rejects_input_over_the_definite_overflow() {
        let input = vec![0u8; DEFINITE_OVERFLOW + 1];
        let mut out = vec![0u8; BUFFER_SIZE];
        assert_eq!(compress(&input, &mut out), 0);
    }
