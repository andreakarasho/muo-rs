/// Huffman-compresses `input` into `output`; returns the compressed length, or 0 when the input is too
/// long or the output too small.
pub fn compress(input: &[u8], output: &mut [u8]) -> usize {
    // Too little room to bound the 4-byte word writes.
    if input.len() > DEFINITE_OVERFLOW || output.len() < 4 {
        return 0;
    }

    let entry = |b: usize| (RAW_TABLE[b * 2] as u32, RAW_TABLE[b * 2 + 1] as u64);
    let safe_output_length = output.len() - 4;
    let mut bit_value: u64 = 0;
    let mut bit_count: u32 = 0;
    let mut out_idx = 0usize;

    for &byte in input {
        let (len, val) = entry(byte as usize);
        bit_value = (bit_value << len) | val;
        bit_count += len;

        if bit_count >= 32 {
            if out_idx > safe_output_length {
                return 0;
            }
            bit_count -= 32;
            let word = (bit_value >> bit_count) as u32;
            output[out_idx..out_idx + 4].copy_from_slice(&word.to_be_bytes());
            out_idx += 4;
        }
    }

    // Terminal code
    let (len, val) = entry(256);
    bit_value = (bit_value << len) | val;
    bit_count += len;

    let remainder = bit_count & 7;
    if remainder != 0 {
        let padding = 8 - remainder;
        bit_value <<= padding;
        bit_count += padding;
    }
    bit_value <<= 64 - bit_count;

    while bit_count > 0 {
        if out_idx >= output.len() {
            return 0;
        }
        output[out_idx] = (bit_value >> 56) as u8;
        out_idx += 1;
        bit_value <<= 8;
        bit_count -= 8;
    }

    out_idx
}

