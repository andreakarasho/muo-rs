// Optimal compression ratio is 2 / 8; worst compression ratio is 11 / 8.
const MINIMAL_CODE_LENGTH: usize = 2;
// Fixed overhead, in bits, per compression call.
const TERMINAL_CODE_LENGTH: usize = 4;

/// `compress` returns 0 for longer input regardless of the output slice.
