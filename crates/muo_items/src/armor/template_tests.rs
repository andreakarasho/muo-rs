#[test]
fn templated_classes_have_their_steps_and_props() {
    let t = templates::table(&mut World::new());
    for name in TEMPLATED {
        assert!(
            t.get(Kind::Item, name)
                .is_some_and(|t| !t.item_steps.is_empty()),
            "{name}: no template steps"
        );
    }
    for &(name, label, rarity) in LABELS {
        let p = &t.get(Kind::Item, name).expect(name).props;
        let int = |k: &str| p.get(k).and_then(|v| v.as_i64()).unwrap_or(0);
        assert_eq!(
            (int("labelNumber"), int("artifactRarity")),
            (label, rarity),
            "{name}"
        );
    }
}
