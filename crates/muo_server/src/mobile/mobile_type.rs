impl MobileType {
    /// The family vtable of type `F`, if this class has one.
    pub fn family<F: std::any::Any>(&self) -> Option<&'static F> {
        self.family?.downcast_ref()
    }

    /// `is`: this class, or any ancestor, is `other`.
    pub fn is(&self, other: &'static MobileType) -> bool {
        let mut t = self;
        loop {
            if std::ptr::eq(t, other) {
                return true;
            }
            match t.parent {
                Some(p) => t = p,
                None => return false,
            }
        }
    }
}

